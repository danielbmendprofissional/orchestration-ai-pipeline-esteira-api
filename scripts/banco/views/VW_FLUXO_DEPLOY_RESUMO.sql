CREATE OR REPLACE VIEW "VW_FLUXO_DEPLOY_RESUMO" AS
SELECT
    f."ID_FLUXO_DEPLOY",
    f."IND_STATUS",
    f."DAT_INICIO",
    f."DAT_FIM",
    f."DSC_USUARIO_CRIACAO",
    f."SGL_SISTEMA",
    f."DSC_VERSAO",
    (SELECT string_agg(DISTINCT d."DSC_LINGUAGEM", ', ')
       FROM "DEPLOY" d WHERE d."ID_FLUXO_DEPLOY" = f."ID_FLUXO_DEPLOY") AS "DSC_LINGUAGENS",
    (SELECT string_agg(DISTINCT d."DSC_PROJETO_GIT", ', ')
       FROM "DEPLOY" d WHERE d."ID_FLUXO_DEPLOY" = f."ID_FLUXO_DEPLOY") AS "DSC_PROJETOS_GIT",
    COALESCE(v."CRITICA", 0) AS "NUM_VULN_CRITICA",
    COALESCE(v."ALTA", 0) AS "NUM_VULN_ALTA",
    COALESCE(v."MEDIA", 0) AS "NUM_VULN_MEDIA",
    COALESCE(v."BAIXA", 0) AS "NUM_VULN_BAIXA",
    (SELECT string_agg(n."COD_TAREFA"::text, ', ' ORDER BY n."COD_TAREFA")
       FROM "FLUXO_DEPLOY_APROV_NEG" n WHERE n."ID_FLUXO_DEPLOY" = f."ID_FLUXO_DEPLOY") AS "DSC_TAREFAS_NEGOCIO",
    (SELECT string_agg(a."DSC_EQUIPE_TECNICA" || ': ' || a."DSC_USUARIO_APROVADOR"
                       || CASE WHEN t."IND_APROVADO" = 'S' THEN ' (aprovado)' ELSE ' (reprovado)' END, ', ')
       FROM "FLUXO_DEPLOY_APROV_TEC" t
       JOIN "APROVADOR_TECNICO" a ON a."ID_APROVADOR_TECNICO" = t."ID_APROVADOR_TECNICO"
      WHERE t."ID_FLUXO_DEPLOY" = f."ID_FLUXO_DEPLOY") AS "DSC_APROVACAO_TECNICA",
    (SELECT string_agg(c."DSC_CRS", ', ')
       FROM "FLUXO_DEPLOY_BD_CRS" c WHERE c."ID_FLUXO_DEPLOY" = f."ID_FLUXO_DEPLOY") AS "DSC_CRS",
    (SELECT string_agg(e."SGL_ETAPA" || ': ' || e."IND_STATUS", ', ' ORDER BY e."NUM_ORDEM")
       FROM "FLUXO_DEPLOY_ETAPA" e WHERE e."ID_FLUXO_DEPLOY" = f."ID_FLUXO_DEPLOY") AS "DSC_ETAPAS",
    (SELECT COALESCE(g."DSC_URL_GMUD", g."DSC_JUSTIFICATIVA")
       FROM "FLUXO_DEPLOY_GMUD" g WHERE g."ID_FLUXO_DEPLOY" = f."ID_FLUXO_DEPLOY") AS "DSC_GMUDS",
    (SELECT r."COD_PROJETO"::text || '/' || r."COD_VERSAO"::text
       FROM "FLUXO_DEPLOY_VERSAO_TAREFAS" r WHERE r."ID_FLUXO_DEPLOY" = f."ID_FLUXO_DEPLOY") AS "DSC_VERSOES_TAREFAS"
FROM "FLUXO_DEPLOY" f
LEFT JOIN (
    SELECT d."ID_FLUXO_DEPLOY",
           SUM(an."NUM_VULNERABILIDADE_CRITICA")::int AS "CRITICA",
           SUM(an."NUM_VULNERABILIDADE_ALTA")::int AS "ALTA",
           SUM(an."NUM_VULNERABILIDADE_MEDIA")::int AS "MEDIA",
           SUM(an."NUM_VULNERABILIDADE_BAIXA")::int AS "BAIXA"
      FROM "DEPLOY" d
      JOIN "ANALISE" an ON an."ID_DEPLOY" = d."ID_DEPLOY"
     WHERE an."IND_STATUS" IN ('CONCLUIDO', 'EXECUTANDO', 'ERRO')
     GROUP BY d."ID_FLUXO_DEPLOY"
) v ON v."ID_FLUXO_DEPLOY" = f."ID_FLUXO_DEPLOY";